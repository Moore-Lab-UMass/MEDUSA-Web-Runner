'use client';
import { useEffect, useState } from 'react';
import Alert from '@mui/material/Alert';
import Box from '@mui/material/Box';
import Button from '@mui/material/Button';
import CircularProgress from '@mui/material/CircularProgress';
import Dialog from '@mui/material/Dialog';
import DialogActions from '@mui/material/DialogActions';
import DialogContent from '@mui/material/DialogContent';
import DialogTitle from '@mui/material/DialogTitle';
import Typography from '@mui/material/Typography';
import DownloadIcon from '@mui/icons-material/Download';
import { getOutputUrls } from '@/common/medusaApi';
import { RunOutput } from '@/types';

type OutputsState =
  | { status: 'loading' }
  | { status: 'error'; message: string }
  | { status: 'ready'; outputs: RunOutput[] };

// Mounted each time the dialog opens, so the signed URLs (which expire) are always fresh.
function OutputFiles({ runId }: { runId: string }) {
  const [state, setState] = useState<OutputsState>({ status: 'loading' });

  useEffect(() => {
    const controller = new AbortController();
    getOutputUrls(runId, controller.signal)
      .then(({ outputs }) => setState({ status: 'ready', outputs }))
      .catch((error) => {
        if (controller.signal.aborted) return;
        setState({ status: 'error', message: error instanceof Error ? error.message : 'Could not load output files.' });
      });
    return () => controller.abort();
  }, [runId]);

  if (state.status === 'loading') {
    return (
      <Box sx={{ display: 'flex', justifyContent: 'center', py: 4 }}>
        <CircularProgress size={28} />
      </Box>
    );
  }
  if (state.status === 'error') return <Alert severity="error">{state.message}</Alert>;

  const plots = state.outputs.filter((output) => output.filename.toLowerCase().endsWith('.png'));

  return (
    <>
      <Box sx={{ display: 'flex', flexDirection: 'column', gap: 1 }}>
        {state.outputs.map(({ filename, url }) => (
          <Box
            key={filename}
            sx={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: 2,
              border: '1px solid #e5e7ea',
              borderRadius: 1.5,
              px: 2,
              py: 1,
            }}
          >
            <Typography noWrap sx={{ fontSize: 13, minWidth: 0 }}>{filename}</Typography>
            <Button
              component="a"
              href={url}
              target="_blank"
              rel="noopener noreferrer"
              size="small"
              startIcon={<DownloadIcon sx={{ fontSize: 15 }} />}
              sx={{ flexShrink: 0 }}
            >
              Download
            </Button>
          </Box>
        ))}
      </Box>

      {/* Temporary: the worker's own renderings, for checking this app's plots against. */}
      {plots.length > 0 && (
        <Box sx={{ mt: 3 }}>
          <Typography sx={{ fontWeight: 600, fontSize: 14 }}>Backend plots</Typography>
          <Typography sx={{ fontSize: 12, color: '#888', mb: 1.5 }}>
            Rendered by the MEDUSA worker, for comparison with the plots on this page.
          </Typography>
          {plots.map(({ filename, url }) => (
            <Box key={filename} sx={{ mb: 2 }}>
              <Typography sx={{ fontSize: 12.5, color: '#666', mb: 0.5 }}>{filename}</Typography>
              {/* A plain img: the signed URL expires, so it must not go through Next's image optimizer */}
              <Box
                component="img"
                src={url}
                alt={`${filename} generated by the MEDUSA worker`}
                sx={{ display: 'block', maxWidth: '100%', border: '1px solid #e5e7ea', borderRadius: 1.5 }}
              />
            </Box>
          ))}
        </Box>
      )}
    </>
  );
}

export default function OutputFilesDialog({
  runId,
  open,
  onClose,
}: {
  runId: string;
  open: boolean;
  onClose: () => void;
}) {
  return (
    <Dialog open={open} onClose={onClose} maxWidth="md" fullWidth>
      <DialogTitle>Output files</DialogTitle>
      <DialogContent dividers>
        <OutputFiles runId={runId} />
      </DialogContent>
      <DialogActions>
        <Button onClick={onClose}>Close</Button>
      </DialogActions>
    </Dialog>
  );
}
